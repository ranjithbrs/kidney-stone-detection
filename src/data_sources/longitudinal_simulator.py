"""NEFROAI-X Synthetic Longitudinal Data Simulator for Engine 3 Software Testing.

Provides deterministic synthetic longitudinal patient records exclusively for
unit testing, continuous integration, and algorithmic stress testing.

CRITICAL REGULATORY & METHODOLOGICAL SAFEGUARDS:
- Synthetic observations generated by this module are SOFTWARE TEST FIXTURES ONLY.
- They MUST NEVER be described, labeled, or treated as real human clinical records.
- They MUST NEVER be used to train or evaluate clinical performance claims.
- The simulator does NOT claim calibration to real patient data (CRIC, NHANES, etc.).
- Provenance is explicitly tagged as 'SYNTHETIC_TEST_FIXTURE_NEFROAI_X'.
"""

from __future__ import annotations

import logging
from datetime import datetime, timedelta, timezone
from typing import Any, Dict, List, Optional, Union

import numpy as np

from src.clinical.progression_features import (
    ClinicalObservation,
    LongitudinalPatientRecord,
)

logger = logging.getLogger("nefroai.longitudinal_simulator")

SYNTHETIC_PROVENANCE_TAG = "SYNTHETIC_TEST_FIXTURE_NEFROAI_X"
SYNTHETIC_DISCLAIMER = (
    "DISCLAIMER: This record is an entirely synthetic software test fixture "
    "generated for automated pipeline verification. It contains no human clinical "
    "data and must not be used for diagnostic, prognostic, or clinical research inference."
)


class LongitudinalDataSimulator:
    """Configurable synthetic longitudinal patient record simulator for testing.

    Parameters
    ----------
    random_seed : Optional[int], default=42
        Integer seed to guarantee strictly deterministic, reproducible outputs.
    """

    def __init__(self, random_seed: Optional[int] = 42) -> None:
        self.random_seed = random_seed
        self.rng = np.random.default_rng(random_seed)

    def reset_seed(self, seed: Optional[int] = None) -> None:
        """Reset the internal pseudo-random number generator seed."""
        target_seed = seed if seed is not None else self.random_seed
        self.rng = np.random.default_rng(target_seed)

    def generate_patient_record(
        self,
        patient_id: str,
        trajectory_type: str = "stable",
        num_visits: int = 5,
        total_followup_years: float = 3.0,
        base_date: Optional[datetime] = None,
        missing_uacr_rate: float = 0.0,
        missing_bp_rate: float = 0.0,
        missing_hba1c_rate: float = 0.0,
        age: Optional[float] = None,
        sex: Optional[str] = None,
        baseline_egfr: Optional[float] = None,
        diabetes: Optional[bool] = None,
        hypertension: Optional[bool] = None,
    ) -> LongitudinalPatientRecord:
        """Generate a single synthetic longitudinal patient record.

        Parameters
        ----------
        patient_id : str
            Identifier string for the synthetic patient.
        trajectory_type : str
            Trajectory pattern preset:
            - 'stable': Normal physiological decline (~ -0.5 to -1.0 mL/min/yr).
            - 'declining' or 'rapid_progressor': Rapid decline (~ -4.0 to -6.5 mL/min/yr).
            - 'variable' or 'fluctuating': High biological variability with fluctuations.
        num_visits : int, default=5
            Number of distinct observation visits to simulate.
        total_followup_years : float, default=3.0
            Total time span in years between first and last visit.
        base_date : Optional[datetime]
            Starting timestamp for baseline visit. Defaults to 2021-01-01 09:00:00 UTC.
        missing_uacr_rate : float, default=0.0
            Probability (0.0 to 1.0) of any visit missing UACR.
        missing_bp_rate : float, default=0.0
            Probability (0.0 to 1.0) of any visit missing blood pressure.
        missing_hba1c_rate : float, default=0.0
            Probability (0.0 to 1.0) of any visit missing HbA1c.
        age : Optional[float]
            Baseline age in years. If None, drawn from Uniform(35, 75).
        sex : Optional[str]
            Biological sex ('male' or 'female'). If None, chosen uniformly.
        baseline_egfr : Optional[float]
            Starting eGFR in mL/min/1.73 m2. If None, drawn from plausible CKD domain.
        diabetes : Optional[bool]
            Documented diabetes mellitus history.
        hypertension : Optional[bool]
            Documented hypertension history.

        Returns
        -------
        LongitudinalPatientRecord
            Fully populated synthetic patient record with explicit synthetic provenance.
        """
        # 1. Demographics & Baseline Covariates
        pt_age = float(age) if age is not None else float(self.rng.uniform(35.0, 75.0))
        pt_sex = sex if sex is not None else self.rng.choice(["male", "female"])
        has_dm = bool(diabetes) if diabetes is not None else bool(self.rng.choice([True, False], p=[0.4, 0.6]))
        has_htn = bool(hypertension) if hypertension is not None else bool(self.rng.choice([True, False], p=[0.7, 0.3]))

        # Base timestamp
        if base_date is None:
            t0 = datetime(2021, 1, 15, 9, 0, 0, tzinfo=timezone.utc)
        else:
            t0 = base_date if base_date.tzinfo else base_date.replace(tzinfo=timezone.utc)

        # 2. Trajectory Annualized Slope & Noise Setup
        traj = trajectory_type.lower()
        if traj in ("stable", "normal"):
            slope = float(self.rng.normal(-0.75, 0.25))
            noise_sd = 1.5
            base_gfr = float(baseline_egfr) if baseline_egfr is not None else float(self.rng.uniform(60.0, 95.0))
            base_uacr = float(self.rng.uniform(10.0, 80.0))
            uacr_growth_rate = 1.05
        elif traj in ("declining", "rapid_progressor", "rapid"):
            slope = float(self.rng.normal(-5.0, 1.0))
            noise_sd = 2.5
            base_gfr = float(baseline_egfr) if baseline_egfr is not None else float(self.rng.uniform(40.0, 70.0))
            base_uacr = float(self.rng.uniform(150.0, 800.0))
            uacr_growth_rate = 1.25
        elif traj in ("variable", "fluctuating"):
            slope = float(self.rng.normal(-2.0, 0.8))
            noise_sd = 7.0  # High noise to trigger high CV
            base_gfr = float(baseline_egfr) if baseline_egfr is not None else float(self.rng.uniform(45.0, 80.0))
            base_uacr = float(self.rng.uniform(50.0, 300.0))
            uacr_growth_rate = 1.10
        else:
            # Default fall-through
            slope = -1.5
            noise_sd = 2.0
            base_gfr = float(baseline_egfr) if baseline_egfr is not None else 65.0
            base_uacr = 45.0
            uacr_growth_rate = 1.1

        # 3. Generate Irregular Visit Timestamps
        if num_visits <= 1:
            visit_times = [t0]
        else:
            # Partition follow-up time into irregular intervals with random jitter
            total_days = total_followup_years * 365.25
            nominal_interval = total_days / (num_visits - 1)
            visit_times = [t0]
            curr_time = t0

            for v in range(1, num_visits - 1):
                # Add log-normal/normal jitter around nominal interval, bounded >= 14 days
                jitter = float(self.rng.uniform(0.7, 1.3))
                interval_days = max(14.0, nominal_interval * jitter)
                curr_time = curr_time + timedelta(days=interval_days)
                visit_times.append(curr_time)

            # Ensure the final visit is at or near total_days
            final_time = t0 + timedelta(days=total_days)
            if final_time <= visit_times[-1]:
                final_time = visit_times[-1] + timedelta(days=30.0)
            visit_times.append(final_time)

        # 4. Generate Visit Observations
        observations: List[ClinicalObservation] = []
        curr_uacr = base_uacr

        for v_idx, v_time in enumerate(visit_times):
            t_from_t0_yr = (v_time - t0).total_seconds() / (365.25 * 86400.0)

            # True underlying trajectory + random biological fluctuation
            true_gfr = base_gfr + (slope * t_from_t0_yr)
            observed_gfr = max(5.0, min(140.0, true_gfr + float(self.rng.normal(0, noise_sd))))

            # Invert eGFR to get plausible synthetic serum creatinine (approximate inverse)
            # Using standard male/female median kappa parameters
            kappa = 0.7 if pt_sex == "female" else 0.9
            # Approximate serum creatinine for test observation:
            if observed_gfr >= 90.0:
                approx_scr = round(max(0.4, float(self.rng.normal(0.8 if pt_sex == 'male' else 0.7, 0.1))), 2)
            elif observed_gfr >= 60.0:
                approx_scr = round(max(0.6, float(self.rng.normal(1.1 if pt_sex == 'male' else 0.9, 0.1))), 2)
            elif observed_gfr >= 30.0:
                approx_scr = round(max(1.2, float(self.rng.normal(1.8 if pt_sex == 'male' else 1.5, 0.2))), 2)
            else:
                approx_scr = round(max(2.5, float(self.rng.normal(3.5 if pt_sex == 'male' else 3.0, 0.4))), 2)

            # UACR with progressive worsening and biological noise
            if self.rng.uniform(0, 1) < missing_uacr_rate:
                v_uacr = None
            else:
                curr_uacr = max(2.0, curr_uacr * (uacr_growth_rate ** (t_from_t0_yr / max(1.0, num_visits))))
                v_uacr = round(float(curr_uacr * self.rng.uniform(0.85, 1.15)), 1)

            # Blood Pressure
            if self.rng.uniform(0, 1) < missing_bp_rate:
                v_sbp = None
                v_dbp = None
            else:
                base_sbp = 140.0 if has_htn else 122.0
                v_sbp = round(float(self.rng.normal(base_sbp + (slope * -1.5), 8.0)), 0)
                v_dbp = round(float(self.rng.normal(v_sbp * 0.62, 5.0)), 0)

            # HbA1c
            if self.rng.uniform(0, 1) < missing_hba1c_rate:
                v_hba1c = None
            else:
                base_a1c = 7.6 if has_dm else 5.4
                v_hba1c = round(float(self.rng.normal(base_a1c, 0.3)), 1)

            obs = ClinicalObservation(
                timestamp=v_time,
                serum_creatinine=approx_scr,
                egfr=round(observed_gfr, 2),
                uacr=v_uacr,
                systolic_bp=v_sbp,
                diastolic_bp=v_dbp,
                hba1c=v_hba1c,
                notes=f"Synthetic visit {v_idx + 1} ({traj} trajectory preset)",
            )
            observations.append(obs)

        return LongitudinalPatientRecord(
            patient_id=patient_id,
            age_baseline=round(pt_age, 1),
            sex=pt_sex,
            diabetes_history=has_dm,
            hypertension_history=has_htn,
            observations=observations,
            is_synthetic=True,
            provenance=SYNTHETIC_PROVENANCE_TAG,
        )

    def generate_cohort(
        self,
        num_patients: int = 20,
        trajectory_distribution: Optional[Dict[str, float]] = None,
        random_seed: Optional[int] = None,
    ) -> List[LongitudinalPatientRecord]:
        """Generate a synthetic cohort containing diverse patient progression trajectories.

        Parameters
        ----------
        num_patients : int, default=20
            Total number of synthetic patient records to generate.
        trajectory_distribution : Optional[Dict[str, float]]
            Proportions of trajectory types. Defaults to 50% stable, 30% declining,
            and 20% variable.
        random_seed : Optional[int]
            Optional seed override for cohort generation.

        Returns
        -------
        List[LongitudinalPatientRecord]
            List of generated synthetic patient records.
        """
        if random_seed is not None:
            self.reset_seed(random_seed)

        dist = trajectory_distribution or {
            "stable": 0.50,
            "declining": 0.30,
            "variable": 0.20,
        }

        # Normalize probabilities
        traj_names = list(dist.keys())
        probs = np.array(list(dist.values()))
        probs = probs / np.sum(probs)

        cohort: List[LongitudinalPatientRecord] = []
        for i in range(num_patients):
            pt_id = f"SYNTH_PT_{i + 1:04d}"
            traj = str(self.rng.choice(traj_names, p=probs))
            n_visits = int(self.rng.integers(3, 8))
            fup_yrs = float(self.rng.uniform(1.5, 5.0))
            record = self.generate_patient_record(
                patient_id=pt_id,
                trajectory_type=traj,
                num_visits=n_visits,
                total_followup_years=fup_yrs,
            )
            cohort.append(record)

        return cohort

    def generate_edge_case(
        self,
        scenario: str,
        patient_id: str = "EDGE_001",
    ) -> LongitudinalPatientRecord:
        """Generate specialized edge cases designed to test validation and abstention.

        Parameters
        ----------
        scenario : str
            One of:
            - 'single_observation': Exactly 1 observation (triggers K < 2 abstention).
            - 'short_followup': 2 observations spanning 30 days (triggers < 90 day abstention).
            - 'non_monotonic': Out-of-order timestamps (triggers non-monotonic abstention).
            - 'duplicate_timestamps': Identical timestamps for two visits.
            - 'missing_creatinine': All observations lack creatinine and eGFR.
            - 'zero_uacr_baseline': Baseline UACR is 0.0 mg/g (tests div-by-zero protection).
            - 'insufficient_for_slope': 2 observations spanning 180 days (eligible for basic features, but slope is None).
        patient_id : str
            Identifier for the generated edge-case record.

        Returns
        -------
        LongitudinalPatientRecord
            Edge-case record.
        """
        t0 = datetime(2022, 1, 10, 9, 0, 0, tzinfo=timezone.utc)

        if scenario == "single_observation":
            obs = [
                ClinicalObservation(
                    timestamp=t0,
                    serum_creatinine=1.1,
                    egfr=75.0,
                    uacr=30.0,
                    systolic_bp=128.0,
                    diastolic_bp=82.0,
                )
            ]
            return LongitudinalPatientRecord(
                patient_id=patient_id,
                age_baseline=58.0,
                sex="male",
                observations=obs,
                is_synthetic=True,
                provenance=SYNTHETIC_PROVENANCE_TAG,
            )

        elif scenario == "short_followup":
            obs = [
                ClinicalObservation(timestamp=t0, serum_creatinine=1.2, egfr=70.0, uacr=45.0),
                ClinicalObservation(
                    timestamp=t0 + timedelta(days=30),  # Only 30 days
                    serum_creatinine=1.25,
                    egfr=68.0,
                    uacr=50.0,
                ),
            ]
            return LongitudinalPatientRecord(
                patient_id=patient_id,
                age_baseline=62.0,
                sex="female",
                observations=obs,
                is_synthetic=True,
                provenance=SYNTHETIC_PROVENANCE_TAG,
            )

        elif scenario == "non_monotonic":
            obs = [
                ClinicalObservation(timestamp=t0, serum_creatinine=1.2, egfr=70.0, uacr=45.0),
                ClinicalObservation(
                    timestamp=t0 - timedelta(days=10),  # Inverted timestamp!
                    serum_creatinine=1.3,
                    egfr=65.0,
                    uacr=55.0,
                ),
            ]
            return LongitudinalPatientRecord(
                patient_id=patient_id,
                age_baseline=60.0,
                sex="male",
                observations=obs,
                is_synthetic=True,
                provenance=SYNTHETIC_PROVENANCE_TAG,
            )

        elif scenario == "duplicate_timestamps":
            obs = [
                ClinicalObservation(timestamp=t0, serum_creatinine=1.2, egfr=70.0, uacr=45.0),
                ClinicalObservation(
                    timestamp=t0,  # Duplicate!
                    serum_creatinine=1.25,
                    egfr=68.0,
                    uacr=50.0,
                ),
            ]
            return LongitudinalPatientRecord(
                patient_id=patient_id,
                age_baseline=60.0,
                sex="female",
                observations=obs,
                is_synthetic=True,
                provenance=SYNTHETIC_PROVENANCE_TAG,
            )

        elif scenario == "missing_creatinine":
            obs = [
                ClinicalObservation(timestamp=t0, serum_creatinine=None, egfr=None, uacr=40.0),
                ClinicalObservation(timestamp=t0 + timedelta(days=120), serum_creatinine=None, egfr=None, uacr=50.0),
            ]
            return LongitudinalPatientRecord(
                patient_id=patient_id,
                age_baseline=55.0,
                sex="male",
                observations=obs,
                is_synthetic=True,
                provenance=SYNTHETIC_PROVENANCE_TAG,
            )

        elif scenario == "zero_uacr_baseline":
            obs = [
                ClinicalObservation(timestamp=t0, serum_creatinine=1.1, egfr=75.0, uacr=0.0),  # Zero UACR baseline!
                ClinicalObservation(timestamp=t0 + timedelta(days=180), serum_creatinine=1.15, egfr=72.0, uacr=25.0),
            ]
            return LongitudinalPatientRecord(
                patient_id=patient_id,
                age_baseline=50.0,
                sex="female",
                observations=obs,
                is_synthetic=True,
                provenance=SYNTHETIC_PROVENANCE_TAG,
            )

        elif scenario == "insufficient_for_slope":
            # 2 observations spanning 180 days: eligible for progression features, but slope is None!
            obs = [
                ClinicalObservation(timestamp=t0, serum_creatinine=1.2, egfr=65.0, uacr=60.0),
                ClinicalObservation(timestamp=t0 + timedelta(days=180), serum_creatinine=1.25, egfr=62.0, uacr=70.0),
            ]
            return LongitudinalPatientRecord(
                patient_id=patient_id,
                age_baseline=64.0,
                sex="male",
                observations=obs,
                is_synthetic=True,
                provenance=SYNTHETIC_PROVENANCE_TAG,
            )

        else:
            raise ValueError(f"Unknown synthetic edge case scenario: '{scenario}'")
